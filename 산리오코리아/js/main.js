// =====================================================
// main.js : 메인 페이지 전용 기능 (메인 배너)
// - 메인 배너 이미지(.main-visual-img)가 있는 페이지에서만 동작
// - common.js 다음에 불러온다. (변수명은 common.js 와 겹치지 않게!)
// =====================================================

// 요구사항
// -> 상단 배너 클릭시
// 상단 메뉴 배경색을 변경하고
// 상단 메뉴는 360도 회전함
// 트랜지션으로 애니메이션 2초간 되게함

// 대상선정:
// 1. 이벤트 대상 : 상단배너 (.main-visual-img)
let 너를클릭해 = document.querySelector('.main-visual-img');
// 2. 변경대상 : 상단영역(.top-area)
let 나야나 = document.querySelector('.top-area');

// 페이지 전용 요소가 없으면 아래 코드는 실행하지 않는다!
// (없는 요소에 .onclick 을 넣으면 오류가 나기 때문)
if (너를클릭해 && 나야나) {
  console.log('나는 누구인가?', 나야나);

  // const 는 상수 또는 함수를 담는 변수선언
  const 나야나함수 = (색상) => {
    console.log('함수호출! 전달값은?', 색상);
    // 상단요소의 배경색 바꾸기
    나야나.style.backgroundColor = 색상;
    나야나.style.transition = '2s ease-in-out';
    // 회전은 로고가 하도록 변경
    const 로고 = 나야나.querySelector('.logo-box');
    if (로고) {
      로고.style.rotate = '360deg';
      // 로고 트랜지션 : 2초후 1초간 ease-in-out
      로고.style.transition = '1s ease-in-out 2s';
    }
  }; ///////// 나야나함수 /////////

  // 3. 이벤트 설정하기 : 클릭이벤트
  너를클릭해.onclick = () => {
    // 해당요소에 클릭이벤트가 발생하면 이 구역을 실행함
    나야나함수('orange');
  }; ///// onclik 함수 ///////
} ///////// if /////////

// =====================================================
// 플레이스 영역 배경 슬라이드 (바닐라JS)
// - 첫번째 이미지 표시 -> 2초 대기 -> 1초간 오른쪽에서 들어옴 -> 반복
// - 마지막 이미지 뒤에 첫번째 복제본을 붙여 자연스럽게 처음으로 이어지게 함
// - 변수가 common.js 와 겹치지 않게 즉시실행함수로 감싼다.
// =====================================================
// (()=>{코드})() -> 변수명 중복 위험을 없애준다!
// 이 구역은 바로 실행됨! 중괄호안이 지역변수가 됨!
// 전역변수는 함수바깥에 있는 변수
// 지역변수는 함수 내부에 있는 변수
// 아래처럼 쓰고 중괄호안에 코드를 넣으면 된다!
/* 
      (()=>{
          내코드...

      })();
*/


(() => {
  const 트랙 = document.querySelector('.place-slide-track');
  if (!트랙 || 트랙.children.length < 2) return;

  const 원본개수 = 트랙.children.length; // 3
  // 첫번째 박스 복제본을 맨 끝에 추가 (3번 -> 1번으로 이어지는 용도)
  트랙.appendChild(트랙.children[0].cloneNode(true));

  const 대기시간 = 2000; // 2초 대기
  const 이동시간 = 1000; // 1초 이동
  let 현재번호 = 0;

  // 한 칸 이동 (오른쪽에서 왼쪽으로 들어옴)
  const 이동 = () => {
    현재번호++;
    트랙.style.transition = `transform ${이동시간}ms ease-in-out`;
    트랙.style.transform = `translateX(-${현재번호 * 100}%)`;

    setTimeout(() => {
      // 복제본(마지막)에 도착하면 트랜지션 없이 처음으로 순간이동
      if (현재번호 === 원본개수) {
        현재번호 = 0;
        트랙.style.transition = 'none';
        트랙.style.transform = 'translateX(0)';
        void 트랙.offsetWidth; // 강제 리플로우 : 위 변경을 즉시 적용
      }
      setTimeout(이동, 대기시간); // 2초 후 다음 이동
    }, 이동시간);
  }; ///////// 이동 함수 /////////

  setTimeout(이동, 대기시간); // 처음엔 2초 후 시작
})(); ///////// 플레이스 슬라이드 /////////